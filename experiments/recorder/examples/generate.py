"""Generate the B0/B1/B2 synthetic example runs.

    python3 -m experiments.recorder.examples.generate [--root DIR] [--quiet]

Writes one run per baseline under ``data/public/`` and ``data/private/``,
every row marked ``data_origin: "synthetic_fixture"`` with a ``synthetic-``
run_id. Deterministic: a fixed run_id and a fixed clock, so re-running
produces byte-identical files. That is what makes "public records can be
regenerated" checkable rather than asserted.

These runs demonstrate and test the recorder. They are not experimental
results and must never be cited as such.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path
from typing import Dict, List, Optional

from .. import paths as paths_mod
from ..adapters import for_baseline
from ..provenance import environment_report, repo_root, software_revision
from ..writers import ExperimentRecorder
from . import w1_fixtures

#: One fixed run per baseline so regeneration is idempotent.
RUNS = {
    "B0": ("baselines/b0-w1-example", "synthetic-20260301T120000Z-b0"),
    "B1": ("baselines/b1-w1-example", "synthetic-20260301T120000Z-b1"),
    "B2": ("baselines/b2-w1-example", "synthetic-20260301T120000Z-b2"),
}

FIXED_SEED = 424242
FIXED_CLOCK = "2026-03-01T12:30:00Z"

COMPONENTS: Dict[str, Dict[str, object]] = {
    "B0": {
        "entrypoint": None,
        "account_implementation": {
            "kind": "eoa", "version": None,
            "note": "plain externally-owned account; no contract code"},
        "paymaster": None,
        "asset": {"kind": "erc20", "address": w1_fixtures.TOKEN,
                  "decimals": 18},
        "destination": w1_fixtures.DESTINATION,
    },
    "B1": {
        "entrypoint": {"address": w1_fixtures.ENTRYPOINT,
                       "version": w1_fixtures.ENTRYPOINT_VERSION},
        "account_implementation": {
            "kind": "erc4337_smart_account", "version": "fixture",
            "factory": w1_fixtures.FACTORY,
            "note": "placeholder: the real implementation identifier is "
                    "recorded once B1 exists"},
        "paymaster": None,
        "asset": {"kind": "erc20", "address": w1_fixtures.TOKEN,
                  "decimals": 18},
        "destination": w1_fixtures.DESTINATION,
    },
    "B2": {
        "entrypoint": {"address": w1_fixtures.ENTRYPOINT,
                       "version": w1_fixtures.ENTRYPOINT_VERSION},
        "account_implementation": {
            "kind": "erc4337_smart_account", "version": "fixture",
            "factory": w1_fixtures.FACTORY,
            "note": "must be byte-identical to B1's account for the "
                    "comparison to isolate the gas mechanism"},
        "paymaster": {"kind": "observable_paymaster",
                      "address": w1_fixtures.PAYMASTER, "version": "fixture",
                      "privacy_mechanism": None},
        "asset": {"kind": "erc20", "address": w1_fixtures.TOKEN,
                  "decimals": 18},
        "destination": w1_fixtures.DESTINATION,
    },
}

NOTE = (
    "SYNTHETIC FIXTURE, NOT A MEASUREMENT. Generated by "
    "experiments/recorder/examples/generate.py to exercise the recorder for "
    "this baseline. B0/B1/B2 are not implemented in baselines/ (see "
    "docs/baseline-spec.md); no chain was touched and no cost figure here is "
    "real."
)


def generate_one(baseline_id: str, root: Optional[Path] = None,
                 overwrite: bool = True,
                 env_report=None) -> Dict[str, object]:
    experiment_id, run_id = RUNS[baseline_id]
    root = Path(root) if root else repo_root()
    rp = paths_mod.run_paths(experiment_id, run_id, root)

    if overwrite:
        for d in (rp.public_run_dir, rp.private_run_dir):
            if d.exists():
                shutil.rmtree(d)

    observations, bundler_obs, ground_truths = w1_fixtures.build(baseline_id)
    adapter = for_baseline(baseline_id)()
    adapter.chain_id = w1_fixtures.CHAIN_ID

    recorder = ExperimentRecorder(
        experiment_id=experiment_id, run_id=run_id, baseline_id=baseline_id,
        workload_id="W1", seed=FIXED_SEED, chain_id=w1_fixtures.CHAIN_ID,
        components=COMPONENTS[baseline_id], data_origin="synthetic_fixture",
        paths=rp, revision=software_revision(root),
        env_report=env_report or environment_report(root),
        clock=lambda: FIXED_CLOCK,
        notes=NOTE,
    )

    written: Dict[str, List[Dict[str, object]]] = {
        "public_events": [], "bundler_private": [], "ground_truth": []}
    with recorder:
        for obs in observations:
            written["public_events"].append(
                recorder.record_public_event(adapter.public_event(obs)))
        for bobs in bundler_obs:
            written["bundler_private"].append(
                recorder.record_bundler_private(adapter.bundler_private(bobs)))
        for gt in ground_truths:
            written["ground_truth"].append(
                recorder.record_ground_truth(adapter.ground_truth(gt)))

    return {
        "baseline_id": baseline_id,
        "experiment_id": experiment_id,
        "run_id": run_id,
        "counts": {k: len(v) for k, v in written.items()},
        "public_events_path": str(
            rp.public_events_path.relative_to(root)),
        "bundler_private_path": (
            str(rp.bundler_private_path.relative_to(root))
            if rp.bundler_private_path.exists() else None),
        "ground_truth_path": str(rp.ground_truth_path.relative_to(root)),
    }


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=None,
                        help="repository root (default: auto-detected)")
    parser.add_argument("--baseline", action="append", choices=sorted(RUNS),
                        help="generate only these baselines")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    root = Path(args.root) if args.root else repo_root()
    targets = args.baseline or sorted(RUNS)
    env = environment_report(root)  # captured once; identical for all runs
    for baseline_id in targets:
        result = generate_one(baseline_id, root, env_report=env)
        if not args.quiet:
            counts = result["counts"]
            print(f"{baseline_id}: {counts['public_events']} public, "
                  f"{counts['bundler_private']} bundler, "
                  f"{counts['ground_truth']} ground-truth rows")
            print(f"    {result['public_events_path']}")
            if result["bundler_private_path"]:
                print(f"    {result['bundler_private_path']}")
            else:
                print("    (no bundler stream: this baseline has no bundler)")
            print(f"    {result['ground_truth_path']}  [SECRET, gitignored]")
    if not args.quiet:
        print("\nAll rows are synthetic fixtures, not measurements.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
