"""CLI: run the D2 kill-condition experiments and analysis.

    python3 -m experiments.liveness.d2k run --batch <stamp> --exp all
    python3 -m experiments.liveness.d2k analyze --batch <stamp> [--write-doc]

Question A (bounded root history): ``boundary``, ``security``, ``stochastic``, ``retry``,
``bundle``, ``overhead``.
Question B (gas scaling):          ``decomp``, ``envelope``, ``grant``, ``detect``.
``all`` runs them in that order.

Configuration is the frozen D2 pilot config (``experiments/liveness/d2/pilot-config.json``)
MERGED with ``config.json`` here: every shared chain / W1 / B3 parameter is inherited rather
than copied, and each override states its reason. Both digests go into the manifest.

Outputs (a NEW namespace; the frozen pilot's ``d2-pilot`` directories are never written):
    data/private/d2-killcondition/<batch>/<exp>.attempts.jsonl
    data/private/d2-killcondition/<batch>/<exp>.arrivals.jsonl
    results/d2-killcondition/<batch>/raw/<exp>.json
    results/d2-killcondition/<batch>/manifest.json
    results/d2-killcondition/<batch>/tables/*, figures/d2-killcondition/<batch>/*
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
import time
import traceback
from copy import deepcopy
from pathlib import Path
from typing import Any, Dict, List, Optional

from ...recorder.provenance import repo_root
from ..d2.__main__ import load_d2_config

CONFIG_RELPATH = Path("experiments") / "liveness" / "d2k" / "config.json"
NAMESPACE = "d2-killcondition"
HIST_EXPERIMENTS = ("boundary", "security", "stochastic", "retry", "bundle", "overhead")
GAS_EXPERIMENTS = ("decomp", "envelope", "grant", "detect")
ORDER = HIST_EXPERIMENTS + GAS_EXPERIMENTS


def _set_path(d: Dict[str, Any], dotted: str, value: Any) -> None:
    keys = dotted.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = value


def load_config(root: Optional[Path] = None) -> Dict[str, Any]:
    """The frozen pilot config merged with the D2K config; overrides applied explicitly."""
    r = Path(root) if root else repo_root()
    base = deepcopy(load_d2_config(r))
    own = json.loads((r / CONFIG_RELPATH).read_text(encoding="utf-8"))
    cfg = {**base, **{k: v for k, v in own.items() if k != "overrides"}}
    applied = {}
    for dotted, spec in own.get("overrides", {}).items():
        _set_path(cfg, dotted, spec["value"])
        applied[dotted] = spec
    cfg["_inherited_from"] = "experiments/liveness/d2/pilot-config.json"
    cfg["_applied_overrides"] = applied
    cfg["_d2_pilot_config_sha256"] = _digest(base)
    cfg["_d2k_config_sha256"] = _digest(own)
    return cfg


def _digest(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()


def batch_dirs(batch: str, root: Optional[Path] = None) -> Dict[str, Path]:
    r = Path(root) if root else repo_root()
    return {"private": r / "data" / "private" / NAMESPACE / batch,
            "results": r / "results" / NAMESPACE / batch,
            "figures": r / "figures" / NAMESPACE / batch}


def machine_info() -> Dict[str, Any]:
    def sh(cmd: List[str]) -> str:
        try:
            return subprocess.run(cmd, capture_output=True, text=True, timeout=10).stdout.strip()
        except Exception:
            return ""
    return {"platform": platform.platform(), "machine": platform.machine(),
            "python": platform.python_version(), "processor": platform.processor(),
            "logical_cpus": str(__import__("os").cpu_count()),
            "node": sh(["node", "--version"]),
            "anvil": (sh(["anvil", "--version"]).splitlines() or [""])[0],
            "forge": (sh(["forge", "--version"]).splitlines() or [""])[0],
            "git_commit": sh(["git", "rev-parse", "HEAD"]),
            "git_dirty": bool(sh(["git", "status", "--porcelain"]))}


def _update_manifest(dirs: Dict[str, Path], key: str, value: Any, cfg: Dict[str, Any]) -> None:
    path = dirs["results"] / "manifest.json"
    man = json.loads(path.read_text()) if path.is_file() else {
        "namespace": NAMESPACE,
        "d2k_config_sha256": cfg["_d2k_config_sha256"],
        "d2_pilot_config_sha256": cfg["_d2_pilot_config_sha256"],
        "applied_overrides": cfg["_applied_overrides"],
        "config": {k: v for k, v in cfg.items() if not k.startswith("_")},
        "machine": machine_info(), "experiments": {},
        "labels": ["NON-PRODUCTION", "NON-EIP-170-DEPLOYABLE-AS-BUILT", "EVALUATION-ONLY",
                   "EXPERIMENTAL-MITIGATION"],
        "frozen_d2_pilot_batch": "20260915T223607Z (not regenerated by this phase)"}
    man["experiments"][key] = value
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(man, indent=2, sort_keys=True, default=str))


def run_experiment(name: str, cfg: Dict[str, Any], dirs: Dict[str, Path],
                   seeds: List[int]) -> None:
    from .records import ARRIVAL_FIELD_TIERS, FIELD_TIERS, write_jsonl
    raw = dirs["results"] / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    mod = __import__(f"experiments.liveness.d2k.{'exp_hist' if name in HIST_EXPERIMENTS else 'exp_gas'}",
                     fromlist=["*"])
    fn = getattr(mod, f"run_{name}")
    result = fn(cfg, seeds, log=lambda m: print(m, flush=True))
    if "attempts" in result:
        write_jsonl(dirs["private"] / f"{name}.attempts.jsonl", result.pop("attempts"),
                    FIELD_TIERS)
    if "arrivals" in result:
        write_jsonl(dirs["private"] / f"{name}.arrivals.jsonl", result.pop("arrivals"),
                    ARRIVAL_FIELD_TIERS)
    (raw / f"{name}.json").write_text(json.dumps(result, default=str))


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--batch", required=True)
    r.add_argument("--exp", action="append", required=True,
                   choices=ORDER + ("all", "hist", "gas"))
    r.add_argument("--seeds", type=int, default=None, help="use only the first K seeds")
    a = sub.add_parser("analyze")
    a.add_argument("--batch", required=True)
    a.add_argument("--write-doc", action="store_true")
    args = ap.parse_args(argv)
    cfg = load_config()
    dirs = batch_dirs(args.batch)
    if args.cmd == "analyze":
        from . import analysis
        analysis.analyze(args.batch, cfg, dirs, write_doc=args.write_doc)
        return 0
    names: List[str] = []
    for e in args.exp:
        names += (list(ORDER) if e == "all" else list(HIST_EXPERIMENTS) if e == "hist"
                  else list(GAS_EXPERIMENTS) if e == "gas" else [e])
    seeds = cfg["seeds"][: args.seeds] if args.seeds else cfg["seeds"]
    failed = False
    for name in dict.fromkeys(names):
        t = time.time()
        print(f"[d2k] {name} ...", flush=True)
        try:
            run_experiment(name, cfg, dirs, seeds)
            _update_manifest(dirs, name, {"status": "ok", "wall_s": time.time() - t,
                                          "seeds": seeds}, cfg)
            print(f"[d2k] {name} ok ({time.time() - t:.0f}s)", flush=True)
        except Exception:
            failed = True
            tb = traceback.format_exc()
            _update_manifest(dirs, name, {"status": "failed", "wall_s": time.time() - t,
                                          "traceback": tb}, cfg)
            print(tb, file=sys.stderr, flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
