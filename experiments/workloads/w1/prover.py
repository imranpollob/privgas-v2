"""Python side of the real Semaphore v4 / Groth16 prover used by the B3 evaluation.

The proof is generated by ``prover/prove.mjs`` with ``@semaphore-protocol/core``
4.14.2 -- the library and version the frozen B3 fixture generators use
(``baselines/b3_privgas_v1/DEPENDENCIES.md``) -- and verified on chain by B3's
real ``SemaphoreVerifier``. No mock or always-true verifier is involved.

Trusted-setup artifacts (``semaphore-<depth>.wasm`` / ``.zkey``) are the ones the
library itself fetches (``@zk-kit/artifacts``: snark-artifacts.pse.dev, semaphore
artifact version 4.13.0). They are downloaded once into ``prover/.artifacts/``
(gitignored) and their sha256 must equal ``prover/artifacts-pin.json`` before any
proof is generated.

Secrets: the Semaphore identity secret is derived from the (secret) run seed
(``keys.semaphore_identity_secret``), sent to the prover over stdin only, and never
written anywhere. Proof timings are private experiment metadata.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional

from ...recorder.provenance import repo_root

PROVER_DIR = Path("experiments") / "workloads" / "w1" / "prover"
PIN_FILE = "artifacts-pin.json"
SEMAPHORE_CORE_VERSION = "4.14.2"


class ProverUnavailable(RuntimeError):
    """Node, the pinned npm package, or the pinned artifacts are missing."""


def group_depth(size: int) -> int:
    """Semaphore proof depth for a group of ``size`` members.

    ``generateProof`` uses the Merkle-proof length (the LeanIMT depth,
    ceil(log2(size))) and 1 for a one-member group; the frozen single-actor W1
    configuration uses depth 1 for exactly that reason.
    """
    if size < 1:
        raise ValueError("a Semaphore group needs at least one member")
    return max(1, (size - 1).bit_length())


def prover_dir(root: Optional[Path] = None) -> Path:
    return (Path(root) if root else repo_root()) / PROVER_DIR


def load_pin(root: Optional[Path] = None) -> Dict[str, Any]:
    return json.loads((prover_dir(root) / PIN_FILE).read_text(encoding="utf-8"))


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def artifact_paths(depth: int, root: Optional[Path] = None,
                   download: bool = True) -> Dict[str, Path]:
    """Local, sha256-checked wasm/zkey for one tree depth."""
    pin = load_pin(root)
    entry = pin["artifacts"][str(depth)]
    out: Dict[str, Path] = {}
    for kind in ("wasm", "zkey"):
        path = prover_dir(root) / entry[kind]["path"]
        if not path.is_file():
            if not download:
                raise ProverUnavailable(f"{path} missing")
            path.parent.mkdir(parents=True, exist_ok=True)
            with urllib.request.urlopen(entry[kind]["url"], timeout=300) as resp:
                tmp = path.with_suffix(path.suffix + ".part")
                tmp.write_bytes(resp.read())
                tmp.replace(path)
        digest = _sha256(path)
        if digest != entry[kind]["sha256"]:
            raise ProverUnavailable(
                f"{path} sha256 {digest} != pinned {entry[kind]['sha256']}; refusing to "
                "prove with unpinned trusted-setup artifacts")
        out[kind] = path
    return out


def installed_core_version(root: Optional[Path] = None) -> Optional[str]:
    pkg = (prover_dir(root) / "node_modules" / "@semaphore-protocol" / "core"
           / "package.json")
    if not pkg.is_file():
        return None
    return json.loads(pkg.read_text(encoding="utf-8"))["version"]


def ensure_installed(root: Optional[Path] = None) -> None:
    if shutil.which("node") is None:
        raise ProverUnavailable("node is not installed")
    if installed_core_version(root) != SEMAPHORE_CORE_VERSION:
        proc = subprocess.run(["npm", "ci", "--no-audit", "--no-fund"],
                              cwd=prover_dir(root), capture_output=True, text=True)
        if proc.returncode != 0 or installed_core_version(root) != SEMAPHORE_CORE_VERSION:
            raise ProverUnavailable(
                f"npm ci failed in {prover_dir(root)}:\n{proc.stdout}\n{proc.stderr}")


@dataclass
class ProofResult:
    proof: Dict[str, Any]
    group_root: int
    prove_ms: float
    verify_off_chain_ms: float


class SemaphoreProver:
    """A long-lived ``node prove.mjs`` process (one per run)."""

    def __init__(self, root: Optional[Path] = None) -> None:
        self.root = Path(root) if root else repo_root()
        ensure_installed(self.root)
        self.proc: Optional[subprocess.Popen] = None
        self._id = 0
        #: Private timing log: one entry per generated proof.
        self.log: List[Dict[str, Any]] = []

    def __enter__(self) -> "SemaphoreProver":
        self.proc = subprocess.Popen(
            ["node", "prove.mjs"], cwd=prover_dir(self.root), stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, bufsize=1)
        return self

    def __exit__(self, *exc) -> bool:
        if self.proc is not None:
            try:
                self.proc.stdin.close()
                self.proc.wait(timeout=30)
            except subprocess.TimeoutExpired:  # pragma: no cover
                self.proc.kill()
                self.proc.wait()
            for s in (self.proc.stdout, self.proc.stderr):
                if s is not None:
                    s.close()
        return False

    def _request(self, body: Dict[str, Any]) -> Dict[str, Any]:
        if self.proc is None:
            raise RuntimeError("prover process is not running")
        self._id += 1
        self.proc.stdin.write(json.dumps({"id": self._id, **body}) + "\n")
        self.proc.stdin.flush()
        line = self.proc.stdout.readline()
        if not line:
            raise ProverUnavailable(f"prover exited: {self.proc.stderr.read()[:2000]}")
        resp = json.loads(line)
        if not resp.get("ok"):
            raise RuntimeError(f"prover error: {resp.get('error')}")
        return resp

    def commitment(self, identity_secret: str) -> int:
        return int(self._request({"op": "commitment",
                                  "identity_secret": identity_secret})["commitment"])

    def group_root(self, members: List[int]) -> Dict[str, int]:
        """Root and depth of ``new Group(members)`` (members in insertion order)."""
        resp = self._request({"op": "group_root", "members": [str(m) for m in members]})
        return {"root": int(resp["group_root"]), "depth": int(resp["depth"]),
                "size": int(resp["size"])}

    def prove(self, *, identity_secret: str, members: List[int], message: int, scope: int,
              merkle_tree_depth: int, label: str) -> ProofResult:
        arts = artifact_paths(merkle_tree_depth, self.root)
        resp = self._request({
            "op": "prove", "identity_secret": identity_secret,
            "members": [str(m) for m in members], "message": str(message),
            "scope": str(scope), "merkle_tree_depth": merkle_tree_depth,
            "wasm": str(arts["wasm"]), "zkey": str(arts["zkey"])})
        self.log.append({"label": label, "message": hex(message),
                         "prove_ms": resp["prove_ms"],
                         "verify_off_chain_ms": resp["verify_off_chain_ms"],
                         "merkle_tree_depth": merkle_tree_depth,
                         "group_size": len(members)})
        return ProofResult(proof=resp["proof"], group_root=int(resp["group_root"]),
                           prove_ms=resp["prove_ms"],
                           verify_off_chain_ms=resp["verify_off_chain_ms"])
