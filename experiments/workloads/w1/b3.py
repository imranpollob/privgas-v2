def decode_b3_log(log: Mapping[str, Any]) -> Optional[Dict[str, Any]]:
    """Decode the B3 protocol logs; None for anything else."""
    topics = log["topics"]
    t0 = topics[0] if topics else None
    d = abi.data_bytes(log["data"])
    if t0 == T_ANNOUNCE_CALLED:
        scheme, stealth = decode(["uint256", "address"], d)
        return {"event": "AnnounceCalled", "scheme_id": scheme,
                "stealth_address": to_checksum_address(stealth)}
    if t0 == T_ELIGIBILITY_MIRRORED:
        return {"event": "EligibilityMirrored",
                "stealth_address": abi.addr_from_topic(topics[1])}
    if t0 == T_FUNDED:
        forwarded, burned = decode(["uint256", "uint256"], d)
        return {"event": "Funded", "stealth_address": abi.addr_from_topic(topics[1]),
                "forwarded": forwarded, "fee_burned": burned}
    if t0 == T_BOOTSTRAP_SPONSORED:
        return {"event": "BootstrapSponsored",
                "stealth_address": abi.addr_from_topic(topics[1])}
    if t0 == T_ROOT_MIRRORED:
        return {"event": "RootMirrored", "root": int(topics[1], 16)}
    if t0 == T_POOL_DEPOSITED:
        (root,) = decode(["uint256"], d)
        return {"event": "CreditDeposited", "commitment": int(topics[1], 16), "root": root}
    if t0 == T_CREDIT_SPENT:
        return {"event": "CreditSpent", "nullifier": int(topics[1], 16),
                "sender": abi.addr_from_topic(topics[2])}
    return None


def word(n: int) -> str:
    """uint256 -> 0x-prefixed 32-byte lowercase hex (schema hash32 shape)."""
    return "0x" + n.to_bytes(32, "big").hex()


# --- artifacts ----------------------------------------------------------------
_PLACEHOLDER = re.compile(r"__\$[0-9a-f]{34}\$__")


@dataclass(frozen=True)
class B3Artifact:
    name: str
    abi: List[Dict[str, Any]]
    bytecode_hex: str          # creation code, unlinked (may carry placeholders)
    deployed_hex: str          # runtime code, unlinked
    link_references: Mapping[str, Mapping[str, List[Mapping[str, int]]]]
    #: ast id -> [{start, length}] of immutables in the runtime code
    immutable_references: Mapping[str, List[Mapping[str, int]]] = None  # type: ignore
    #: library link offsets in the RUNTIME code (differ from creation-code offsets)
    deployed_link_references: Mapping[str, Mapping[str, List[Mapping[str, int]]]] = None  # type: ignore

    def masked_runtime(self, runtime: bytes) -> bytes:
        """``runtime`` with immutable slots and library links zeroed, for comparing a
        deployed contract with its compiled artifact."""
        code = bytearray(runtime)
        for refs in (self.immutable_references or {}).values():
            for ref in refs:
                code[ref["start"]:ref["start"] + ref["length"]] = bytes(ref["length"])
        for _source, libs in (self.deployed_link_references or {}).items():
            for refs in libs.values():
                for ref in refs:
                    code[ref["start"]:ref["start"] + ref["length"]] = bytes(ref["length"])
        return bytes(code)

    @staticmethod
    def _normalise(h: str) -> bytes:
        return bytes.fromhex(_PLACEHOLDER.sub("0" * 40, h.removeprefix("0x")))

    @property
    def deployed_bytecode(self) -> bytes:
        """Runtime code with link placeholders zeroed (stable across deployments)."""
        return self._normalise(self.deployed_hex)

    @property
    def deployed_bytecode_sha256(self) -> str:
        return hashlib.sha256(self.deployed_bytecode).hexdigest()

    @property
    def runtime_size(self) -> int:
        return len(self.deployed_bytecode)

    def linked_bytecode(self, libraries: Mapping[str, str]) -> bytes:
        code = bytearray(self._normalise(self.bytecode_hex))
        for _source, libs in self.link_references.items():
            for lib, refs in libs.items():
                addr = bytes.fromhex(libraries[lib][2:])
                for ref in refs:
                    code[ref["start"]:ref["start"] + ref["length"]] = addr
        return bytes(code)


def eval_dir(root: Optional[Path] = None) -> Path:
    return (Path(root) if root else repo_root()) / B3_EVAL_DIR


def forge_build_b3(root: Optional[Path] = None) -> str:
    import subprocess
    proc = subprocess.run(["forge", "build"], cwd=eval_dir(root), capture_output=True,
                          text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"forge build (b3_eval) failed:\n{proc.stdout}\n{proc.stderr}")
    return proc.stdout


def load_b3_artifact(name: str, root: Optional[Path] = None,
                     out_dir: Optional[Path] = None) -> B3Artifact:
    file_name, contract = B3_CONTRACTS[name]
    base = out_dir if out_dir is not None else eval_dir(root) / "out"
    data = json.loads((base / file_name / f"{contract}.json").read_text(encoding="utf-8"))
    return B3Artifact(name=name, abi=data["abi"], bytecode_hex=data["bytecode"]["object"],
                      deployed_hex=data["deployedBytecode"]["object"],
                      link_references=data["bytecode"].get("linkReferences", {}),
                      immutable_references=data["deployedBytecode"].get(
                          "immutableReferences", {}),
                      deployed_link_references=data["deployedBytecode"].get(
                          "linkReferences", {}))


def load_b3_all(root: Optional[Path] = None) -> Dict[str, B3Artifact]:
    return {name: load_b3_artifact(name, root) for name in B3_CONTRACTS}


def executable_code(runtime: bytes) -> bytes:
    """Runtime code without the trailing CBOR metadata (source-path dependent)."""
    n = int.from_bytes(runtime[-2:], "big")
    return runtime[:-(n + 2)]


