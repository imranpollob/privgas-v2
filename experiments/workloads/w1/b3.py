# --- deployment -------------------------------------------------------------------


def create_address(sender: str, nonce: int) -> str:
    return to_checksum_address(keccak(rlp.encode([bytes.fromhex(sender[2:]), nonce]))[12:])


@dataclass
class B3Environment:
    poseidon_t3: str
    semaphore_verifier: str
    announcer: str
    credit_paymaster: str
    credit_pool: str
    bootstrap_paymaster: str
    registry: str
    credit_scope: int

    def contracts(self) -> Dict[str, str]:
        return {"PoseidonT3": self.poseidon_t3, "SemaphoreVerifier": self.semaphore_verifier,
                "MockAnnouncer": self.announcer, "CreditPaymaster": self.credit_paymaster,
                "CreditPool": self.credit_pool, "BootstrapPaymaster": self.bootstrap_paymaster,
                "AnnouncementRegistry": self.registry}


def deploy_b3(chain: Chain, deployer, sponsor_operator, *, arts: Mapping[str, B3Artifact],
              b3cfg: B3Config, entrypoint: str, gas: int, call_gas: int) -> B3Environment:
    """Deploy the frozen B3 contracts unchanged and fund both Paymasters (setup)."""

    def deploy(name: str, types: List[str], args: List[Any],
               libraries: Optional[Mapping[str, str]] = None) -> str:
        data = arts[name].linked_bytecode(libraries or {}) + (encode(types, args)
                                                              if types else b"")
        st = chain.send(deployer, label=f"setup_deploy_b3_{name}", phase="setup", to=None,
                        data=data, gas=gas)
        return to_checksum_address(st.receipt["contractAddress"])

    poseidon = deploy("PoseidonT3", [], [])
    verifier = deploy("SemaphoreVerifier", [], [])
    announcer = deploy("MockAnnouncer", [], [])
    n = chain.nonce(deployer.address, "pending")
    credit_pm_addr = create_address(deployer.address, n)
    pool_addr = create_address(deployer.address, n + 1)
    bootstrap_addr = create_address(deployer.address, n + 2)
    registry_addr = create_address(deployer.address, n + 3)
    credit_pm = deploy("CreditPaymaster", ["address", "address", "address"],
                       [entrypoint, pool_addr, verifier])
    pool = deploy("CreditPool", ["address", "address"], [credit_pm_addr, registry_addr],
                  libraries={"PoseidonT3": poseidon})
    bootstrap = deploy("BootstrapPaymaster", ["address", "address", "address", "bytes4"],
                       [entrypoint, registry_addr, pool_addr, abi.selector(SIG_POOL_DEPOSIT)])
    registry = deploy("AnnouncementRegistry",
                      ["address", "address", "address", "uint256", "uint256"],
                      [announcer, bootstrap_addr, pool_addr, b3cfg.v_min,
                       b3cfg.non_refundable_fee])
    if (credit_pm, pool, bootstrap, registry) != (credit_pm_addr, pool_addr, bootstrap_addr,
                                                  registry_addr):
        raise RuntimeError("B3 deployment address drift (precomputed forward addresses)")

    for label, pm in (("setup_b3_bootstrap_paymaster_deposit", bootstrap),
                      ("setup_b3_credit_paymaster_deposit", credit_pm)):
        chain.send(sponsor_operator, label=label, phase="setup", to=entrypoint,
                   data=abi.call(SIG_EP_DEPOSIT_TO, ["address"], [pm]),
                   value=b3cfg.paymaster_deposit, gas=call_gas)

    scope = int(chain.eth_call(credit_pm, abi.selector(SIG_CPM_SCOPE)), 16)
    if scope != int.from_bytes(keccak(text=CREDIT_SCOPE_PREIMAGE), "big"):
        raise RuntimeError("deployed CreditPaymaster scope differs from the frozen source")
    return B3Environment(poseidon_t3=poseidon, semaphore_verifier=verifier,
                         announcer=announcer, credit_paymaster=credit_pm, credit_pool=pool,
                         bootstrap_paymaster=bootstrap, registry=registry,
                         credit_scope=scope)


# --- protocol calldata --------------------------------------------------------------


def ephemeral_public_key(account) -> bytes:
    """33-byte compressed secp256k1 public key (ERC-5564 scheme 1 shape).

    B3 implements no ERC-5564 key derivation (its README and technical report say
    so); the key is seed-derived and announced as the protocol requires, but the
    stealth account is not derived from it.
    """
    return eth_keys.PrivateKey(bytes(account.key)).public_key.to_compressed_bytes()


def announce_and_fund_calldata(scheme_id: int, stealth: str, ephemeral_pubkey: bytes,
                               metadata: bytes) -> bytes:
    return abi.call(SIG_ANNOUNCE_AND_FUND, ["uint256", "address", "bytes", "bytes"],
                    [scheme_id, stealth, ephemeral_pubkey, metadata])


def bootstrap_call_data(credit_pool: str, commitment: int) -> bytes:
    """``execute(creditPool, 0, deposit(commitment))`` -- the only shape B3 sponsors."""
    return abi.call(abi.SIG_ACCOUNT_EXECUTE, ["address", "uint256", "bytes"],
                    [credit_pool, 0, abi.call(SIG_POOL_DEPOSIT, ["uint256"], [commitment])])


def encode_proof(proof: Mapping[str, Any]) -> bytes:
    """``abi.encode(ISemaphore.SemaphoreProof)`` exactly as CreditPaymaster decodes it."""
    return encode([SEMAPHORE_PROOF_TUPLE], [(
        int(proof["merkleTreeDepth"]), int(proof["merkleTreeRoot"]), int(proof["nullifier"]),
        int(proof["message"]), int(proof["scope"]), [int(p) for p in proof["points"]])])


def decode_proof(proof_bytes: bytes) -> Dict[str, Any]:
    (t,) = decode([SEMAPHORE_PROOF_TUPLE], proof_bytes)
    return {"merkle_tree_depth": t[0], "merkle_tree_root": t[1], "nullifier": t[2],
            "message": t[3], "scope": t[4], "points": list(t[5])}


PROOF_BYTE_LENGTH = 13 * 32  # static tuple: 5 uint256 words + uint256[8] = 416 bytes
PLACEHOLDER_PROOF = bytes(PROOF_BYTE_LENGTH)


def view_uint(chain: Chain, to: str, sig: str, types: Tuple[str, ...] = (),
              args: Tuple[Any, ...] = (), block: Any = "latest") -> int:
    data = abi.call(sig, list(types), list(args)) if types else abi.selector(sig)
    return int(chain.eth_call(to, data, block=block), 16)
