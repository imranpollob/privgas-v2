"""The frozen B3 specimen (PrivGas v1) inside the W1 measurement framework.

NON-PRODUCTION | NON-EIP-170-DEPLOYABLE-AS-BUILT | PRIVACY-EVALUATION-ONLY.
Runs only on the ``b3_compat_local`` evaluation profile (``profiles.py``).

Baseline id: ``B3-PrivGas-v1``. It names the UNMODIFIED specimen
``baselines/b3_privgas_v1`` at commit ``02a3f0abdb979446545aa87149080bfb44e43a3e``;
if any protocol source changes, the result is not this baseline.

What this module does and does not do
-------------------------------------
* Compiles nothing of its own design. ``baselines/b3_eval`` compiles the frozen
  sources read-only with the submodule's compiler settings; this module loads
  those artifacts, links ``CreditPool`` against the deployed ``PoseidonT3`` (the
  only link reference), and deploys them in the frozen fixture's order
  (``test/FunctionalCorrectnessFixture.sol``: verifier, announcer, CreditPaymaster,
  CreditPool, BootstrapPaymaster, AnnouncementRegistry, with forward addresses
  precomputed from the deployer nonce).
* Protocol parameters come from the frozen source (``b3-eval-config.json`` records
  where): vMin 0.01 ETH, non-refundable fee 0.021 ETH, scheme id 1, the fixed
  credit scope ``keccak256("stealth-protocol.credit.v1")`` (read back from the
  deployed CreditPaymaster and checked).
* The real ``SemaphoreVerifier`` verifies a real Groth16 proof generated by
  ``prover.py``. No mock verifier.
* The two B3 Paymasters are plain ``IPaymaster`` contracts with no ``deposit()``
  helper, so the sponsor operator funds them with ``EntryPoint.depositTo``.
* No staking: the Paymasters are NOT staked. The in-repo experimental bundler
  enforces no ERC-7562 rules, so this runs; nothing here establishes ERC-7562 or
  production-bundler compatibility.
* ``MockAnnouncer`` is B3's own ERC-5564 Announcer stand-in. It emits
  ``AnnounceCalled(schemeId, stealthAddress)``, not the canonical ERC-5564
  ``Announcement`` event; the ephemeral public key and metadata are still public
  in the ``announceAndFund`` calldata.
"""

